import { DEFAULT_LANGUAGE, INDEXED_LANGUAGES, SUPPORTED_LANGUAGES } from '@/config/translations/translations.config'

// ЕСТЬ ЛИ У СТРАНИЦЫ СОБСТВЕННЫЙ ПЕРЕВОД — ОДИН ОТВЕТ НА ВЕСЬ ПРОЕКТ (256-5).
//
// 🔒 ЗАЧЕМ ЭТО ВООБЩЕ СПРАШИВАЮТ. Страх владельца, сформулированный им дословно
// 2026-09-20: «если у нас появится множество дублей на разных языках, то наш сайт
// немедленно попадёт в блокировки Google как doorway, и вот это хуже, чем не иметь
// этих страниц».
//
// Механизм этого отказа таков. Включённый язык без перевода всё равно получает
// адрес: резолвер честно отдаёт английскую основу, и страница открывается. Для
// человека это неудобство. Для поисковика — набор почти одинаковых адресов, ни
// один из которых не назвал себя оригиналом: ровно определение дорвея. Измерено
// 2026-09-20 живьём — включённый `es` отдал английский текст под `<html lang="es">`.
//
// 🔒 ОТСЮДА ПРАВИЛО, КОТОРОЕ ДЕЛАЕТ ДОРВЕЙ НЕВОЗМОЖНЫМ ПО ПОСТРОЕНИЮ: в индекс и в
// набор `hreflang` попадает только та версия, у которой есть СВОЙ текст. Остальные
// остаются видимыми человеку и невидимыми машине.
//
// 🔒 ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ВЫРАЖЕНИЕ ВНУТРИ `alternates.ts`. Из него пьют
// трое: набор `hreflang`, мета-тег `robots` страницы и карта сайта. Три разных
// ответа на один вопрос — ровно та болезнь, которую лечил примитив коллекции в 254.

/**
 * Форма данных любой публичной страницы: английская основа плюс переводы.
 *
 * Совпадает у главной (`HomeData`), правовых страниц и корневых (`FooterPageData`)
 * — проверено чтением всех трёх, а не предположено.
 */
export type TranslatedPage = {
  overrides?: Record<string, unknown>
}

/**
 * Есть ли у страницы СОБСТВЕННЫЙ перевод на этот язык.
 *
 * 🛑 ВОПРОС НЕ «ВКЛЮЧЁН ЛИ ЯЗЫК» И НЕ «СУЩЕСТВУЕТ ЛИ ФАЙЛ». Ячейка, дословно
 * повторяющая основу, переводом не является: она даёт тот же текст под другим
 * `lang`, то есть ровно тот дубль, от которого защищает весь шаг. Поэтому пустая
 * ячейка (`{}`) считается отсутствующей.
 *
 * Язык по умолчанию переведён всегда — он и есть основа.
 */
export function isTranslated(lang: string, page: TranslatedPage): boolean {
  if (lang === DEFAULT_LANGUAGE) return true
  const cell = page.overrides?.[lang]
  if (!cell || typeof cell !== 'object') return false
  return Object.keys(cell as Record<string, unknown>).length > 0
}

/**
 * Языки, на которых страница существует ПО-НАСТОЯЩЕМУ.
 *
 * 🔒 ПЕРЕСЕЧЕНИЕ С ВКЛЮЧЁННЫМ НАБОРОМ, А НЕ ПРОСТО КЛЮЧИ `overrides`. Перевод,
 * оставшийся в дереве после того, как владелец выключил язык, не имеет адреса:
 * объявить его в `hreflang` значило бы указать на 404. Обратное тоже верно и
 * важнее: включённый язык без перевода в список не попадает.
 */
export function translatedLanguages(page: TranslatedPage): string[] {
  return SUPPORTED_LANGUAGES.filter(lang => isTranslated(lang, page))
}

// ── Открыт ли язык поисковику (шаг 340) ─────────────────────────────────────
//
// 🔒 ИНДЕКСИРУЕТСЯ ТОЛЬКО ТО, ЧТО И ОТКРЫТО, И ПЕРЕВЕДЕНО. Два замка, и ни один не снимает другой: открытый язык без
// своего текста — копия основы (256); переведённый, но не открытый — решение человека «пока не показывать поисковику»
// (340). Три сигнала пьют отсюда: мета-тег robots страницы, набор hreflang и карта сайта. `robots.txt` языки НЕ запрещает:
// «For the noindex rule to be effective, the page… must not be blocked by a robots.txt file» (Google, block-indexing).

/** Открыт ли язык поисковику и есть ли у страницы свой текст на нём. */
export function isIndexable(lang: string, page: TranslatedPage): boolean {
  return INDEXED_LANGUAGES.includes(lang) && isTranslated(lang, page)
}

/** Языки, которые страница предлагает поисковику: взаимный набор hreflang и строки карты. */
export function indexableLanguages(page: TranslatedPage): string[] {
  return SUPPORTED_LANGUAGES.filter(lang => isIndexable(lang, page))
}

/**
 * Набор hreflang, который печатает версия страницы на языке `lang`.
 *
 * 🔒 ЗАКРЫТАЯ ВЕРСИЯ НЕ ОБЪЯВЛЯЕТ ПЕРЕВОДОВ. Её набор поисковик не учитывает (noindex), а открытые версии её не называют —
 * значит её ссылки односторонние по построению. Замер 340-1 на aifa.dev: `/fr` с `noindex` печатал `x-default,en,ru`.
 * Пустой список → `buildAlternates` оставляет только canonical.
 */
export function alternatesLanguages(lang: string, page: TranslatedPage): string[] {
  return isIndexable(lang, page) ? indexableLanguages(page) : []
}
