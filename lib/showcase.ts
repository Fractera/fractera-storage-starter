//
// 🔒 ЧТО ЭТО ЗНАЧИТ ТЕХНИЧЕСКИ. Витрина — не форк, не отдельный стенд и не второй
// набор данных, а ТОТ ЖЕ КОД В ДРУГОМ РЕЖИМЕ, и режим есть СВОЙСТВО АДРЕСА. Из
// одного предиката следуют ровно три вещи: слой архитектора и приватный слой
// открыты на чтение · они же индексируемы · запись запрещена целиком. Новая
// страница наследует режим автоматически и ничего не знает о витрине — прав «на
