//
// 🛑 ЦЕНА НАЗВАНА ВЛАДЕЛЬЦУ ДО СОГЛАСОВАНИЯ И ПРИНЯТА ИМ: режим только для чтения
// защищает данные от ИЗМЕНЕНИЯ и не защищает от ПРОЧТЕНИЯ. Всё, что окажется в
// приватном слое витрины, публично. Отсюда закон, живущий в `CLAUDE.md`: на
// `fractera.ai` не появляется ни одной настоящей записи.
//
// 🛑 ВТОРОЕ СЛЕДСТВИЕ, ТОЖЕ ПРИНЯТОЕ: запрет записи не знает, кто пришёл, поэтому
// владелец тоже не сможет ничего изменить с адреса витрины. Управление остаётся
// на его машине — там работает правило хозяина за клавиатурой.

/**
 * Адрес витрины. **Одно значение на весь проект**, и оно жёстко задано.
 *
 * 🔒 КОНСТАНТА, А НЕ НАСТРОЙКА — И ЭТО ГЛАВНОЕ РЕШЕНИЕ ЭТОГО ФАЙЛА. Настройку
 * правит владелец проекта, значит любой гость объявил бы витриной себя и открыл
 * поисковику свой приватный слой одним полем формы. Константа уезжает в копию как
 * есть и там не совпадает ни с чем, потому что домен у гостя другой: гостевой узел
 * закрыт по умолчанию, и чтобы его открыть, нужно править код, а не настройки.
 */
export const SHOWCASE_ORIGIN = "https://fractera.ai"

/** Имя хоста витрины — выводится из адреса, вторым значением не объявляется. */
export const SHOWCASE_HOSTNAME = SHOWCASE_ORIGIN.replace(/^https?:\/\//, "")

/**
 * Совпадает ли АДРЕС САЙТА с витриной.
 *
 * 🛑 СРАВНИВАЕТСЯ АДРЕС ЦЕЛИКОМ, А НЕ ХВОСТ ИМЕНИ — в отличие от признака
 * временного туннеля (`lib/auth/temporary-address.ts`), где хвост единственно
 * возможен. Здесь наоборот: совпадение по хвосту открыло бы витринный режим любому
 * поддомену, включая тот, что однажды заведёт себе чужой человек.
 *
 * 🛑 ЧТО НЕ СОВПАДЁТ, И ЭТО НАЗВАНО ЗАРАНЕЕ: `www.fractera.ai`, `http://fractera.ai`,
 * любой поддомен, адрес с портом. Слово владельца — «полностью совпадают».
 * Понадобится другое написание — добавляется ЗДЕСЬ и нигде больше.
 */
export function isShowcaseOrigin(url: string | undefined | null): boolean {
  const bare = (url ?? "").trim().toLowerCase().replace(/\/+$/, "")
  return bare === SHOWCASE_ORIGIN
}

/** Принадлежит ли ИМЯ ХОСТА витрине. Порт отбрасывается, регистр не важен. */
export function isShowcaseHostname(hostname: string | undefined | null): boolean {
  const bare = (hostname ?? "").trim().toLowerCase().replace(/:\d+$/, "")
  return bare === SHOWCASE_HOSTNAME
}

/**
 * Пришёл ли запрос НА витрину.
 *
 * Запроса нет (серверный вызов внутри процесса) — `false`: молчаливая выдача прав
 * тому, чьё происхождение неизвестно, и есть тот класс дефекта, которым оплачен
 * `auth-bypass.ts`. Имя хоста берётся так же, как в правиле хозяина и в признаке
 * туннеля: сначала то, что назвал поставленный человеком прокси, потом `Host`.
 */
export function isShowcaseRequest(req?: NextRequest): boolean {
  if (!req) return false
  const forwarded = (req.headers.get("x-forwarded-host") ?? "").trim().toLowerCase()
  const host = (req.headers.get("host") ?? "").trim().toLowerCase()
  return isShowcaseHostname(forwarded || host)
}
