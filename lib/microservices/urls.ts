// значит умолчание не «запасной вариант», а тихий стук в пустоту: служба жива,
// а код зовёт её по адресу серверной линии и получает отказ соединения.
//
// 🔒 ИСТОЧНИК ПРАВДЫ — РЕЕСТР `WEB4-ITEMS-REGISTRY/web4-items.json`, а не память и не окружение.
// Порт туда вписывает установщик — тот, который службу поднял. Спрашивать надо
// его, потому что он единственный знает, на чём она в итоге встала.
//
// 🛑 ОКРУЖЕНИЕ ОСТАЁТСЯ ВТОРЫМ ИСТОЧНИКОМ, И ЭТО НЕ ПОСЛАБЛЕНИЕ. Серверная
// линия `aifa.dev` реестра не имеет вовсе: там службы стоят на 3001 и 3300, а
// адрес приходит переменной. Один и тот же код обслуживает обе линии, поэтому
// переменная читается — но ТОЛЬКО здесь. В остальном коде узла её имя запрещено
// правилом 14 сторожа `check-microservices.mjs`.
//
// 🔒 NULL — ЗАКОННЫЙ ОТВЕТ, И ЗВАТЬ ЕГО НАДО ПО ИМЕНИ. Службы может не быть:
// состав узла — состояние машины, а не константа. Тогда дверь обязана ответить
// честным отказом с названной причиной, а не пятисоткой с пустым телом.

import { serviceUrl } from "./registry"

const trim = (s: string) => s.replace(/\/+$/, "")

/** Адрес службы авторизации так, как её зовёт СЕРВЕРНЫЙ код узла. */
export function authUrl(): string | null {
  const fromRegistry = serviceUrl("auth")
  if (fromRegistry) return trim(fromRegistry)
  const env = process.env.AUTH_SERVICE_URL?.trim()
  return env ? trim(env) : null
}

/** Адрес слоя данных так, как его зовёт СЕРВЕРНЫЙ код узла. */
export function dataUrl(): string | null {
  const fromRegistry = serviceUrl("data")
  if (fromRegistry) return trim(fromRegistry)
  const env = process.env.REMOTE_DATA_URL?.trim()
  return env ? trim(env) : null
}

/**
 * Слой данных стоит НЕ на этой машине. Признак прежний — задана переменная
 * окружения; реестр описывает только соседей по машине, поэтому адрес из него
 * удалённым не бывает по определению.
 */
export function isRemoteData(): boolean {
  return !!process.env.REMOTE_DATA_URL?.trim()
}

/** Текст отказа, когда службы нет. Один на все двери — чтобы причина звучала одинаково. */
export function serviceMissing(id: "auth" | "data"): string {
  return `служба «${id}» не установлена на этом узле: её нет в WEB4-ITEMS-REGISTRY/web4-items.json, и адрес не задан окружением`
}
