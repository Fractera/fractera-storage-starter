// признак РЕЖИМА, вместе с видимой полосой предупреждения.
//
// 🛑 ПОЧЕМУ НЕ «ПРОБНЫЙ РЕЖИМ». Пробный режим — это машина дома ПЛЮС временный
// адрес в интернете. Сними мы замок по признаку режима — слой архитектора
// открылся бы любому, кто знает ссылку `*.trycloudflare.com`: настройки узла,
// терминал, подписка. Признак хозяина такого не даёт: человек за клавиатурой
// этой машины и так владеет файлами, а интернет остаётся под замком.
//
// 🔒 ПРИЗНАК ИЗМЕРЕН, А НЕ ВЫВЕДЕН ИЗ ЗДРАВОГО СМЫСЛА (2026-09-19, замер через
// живой туннель):
//
//   с самой машины → host: "localhost:24680", cf-connecting-ip: нет, cf-ray: нет
//   через туннель  → host: "<имя>.trycloudflare.com", cf-connecting-ip: 31.4.242.62, cf-ray: есть
//
// То есть `cloudflared` НЕ подменяет `Host` адресом источника — а это и было
// единственным, из-за чего правило могло оказаться дырой. Проверять надо было
// обязательно: подменяй он заголовок, «пришёл с localhost» стало бы правдой для
// всего интернета.
//
// 🛑 УСЛОВИЙ ДВА, И ВТОРОЕ — НЕ ПЕРЕСТРАХОВКА. Заголовок `Host` присылает клиент,
// то есть теоретически его можно написать любым. Поэтому к имени хоста добавлена
// проверка на отсутствие собственных заголовков Cloudflare: их ставит сама сеть
// Cloudflare и перезаписывает присланные клиентом. Подделать нужно было бы оба
// признака сразу, причём второй — не своим браузером, а чужой сетью.
//
// 🛑 ЧЕГО ЭТО ПРАВИЛО НЕ ДЕЛАЕТ. Оно не заменяет авторизацию и не раздаёт права
// наружу: за пределами петли всё решает обычный вход. И оно не касается режима
// разработки — тот обходит замок своим путём (`auth-bypass.ts`), и это отдельная
// история со своей ценой.

/** Имена, которыми машина зовёт саму себя. Порт отбрасывается перед сверкой. */
const LOOPBACK = new Set(["localhost", "127.0.0.1", "::1", "[::1]"])

/**
 * Зовёт ли это имя хоста саму машину. Голое имя, без запроса, — потому что тот же
 * вопрос задаёт БРАУЗЕР (`window.location.hostname`) в замке слоя архитектора.
 *
 * 🛑 В БРАУЗЕРЕ ЭТО ВЫВЕСКА, А НЕ ЗАМОК, и разница названа вслух: заголовков
 * Cloudflare клиент не видит и доказать ими ничего не может. Замок остаётся
 * серверным — `isOwnerAtMachine` ниже и ворота `proxy.ts`.
 */
export function isLoopbackHostname(hostname: string): boolean {
  return LOOPBACK.has((hostname ?? "").trim().toLowerCase().replace(/:\d+$/, ""))
}

/**
 * Пришёл ли запрос с самой машины.
 *
 * Запроса нет вовсе (серверный вызов внутри процесса) — отвечаем `false`:
 * молчаливая выдача прав тому, чьё происхождение неизвестно, и есть тот самый
 * класс дефекта, которым оплачен `auth-bypass.ts`.
 */
export function isOwnerAtMachine(req?: NextRequest): boolean {
  if (!req) return false

  // Заголовки самой сети Cloudflare: есть хоть один — запрос пришёл снаружи,
  // и никакой `Host` этого уже не отменяет.
  if (req.headers.get("cf-connecting-ip") || req.headers.get("cf-ray")) return false
  // Прокси, поставленный человеком перед приложением, называет исходный хост
  // здесь. Он тоже означает «не с машины».
  const forwarded = req.headers.get("x-forwarded-host")

  const host = (req.headers.get("host") ?? "").trim().toLowerCase()
  const bare = host.replace(/:\d+$/, "")

  if (forwarded) {
    const fwd = forwarded.split(",")[0].trim().toLowerCase().replace(/:\d+$/, "")
    if (!LOOPBACK.has(fwd)) return false
  }

  return LOOPBACK.has(bare)
}
