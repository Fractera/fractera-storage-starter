import { getAppConfig } from "@/config/app-config"
import { isShowcaseOrigin } from "./showcase"

// СЕРВЕРНАЯ ПОЛОВИНА ПРИЗНАКА ВИТРИНЫ (256-1).
//
// 🔒 ПОЧЕМУ ФАЙЛОВ ДВА, И ЭТО НЕ ВТОРОЙ ИСТОЧНИК ПРАВДЫ. Правило одно и живёт в
// `lib/showcase.ts`: адрес целиком равен `SHOWCASE_ORIGIN`. Здесь только ОТВЕТ НА
// ВОПРОС «ЧЕЙ АДРЕС БРАТЬ» — из настроек на диске.
//
// 🛑 РАЗДЕЛЕНИЕ ВЫНУЖДЕНО СРЕДОЙ ИСПОЛНЕНИЯ, А НЕ ВКУСОМ. `proxy.ts` работает в
// edge-среде, где чтения диска нет вовсе, а `getAppConfig()` читает
// `APP-CONFIG/app-config.json` через `fs`. Ввези прокси этот модуль — сборка
// прокси упала бы на `fs`, и упала бы ПОЗЖЕ, уже в сборке, а не при написании.
// Поэтому запрос спрашивает себя сам (`isShowcaseRequest`), а сборка спрашивает
// настройки (здесь).
//
// 🔒 ДВА ИСТОЧНИКА ОТВЕЧАЮТ НА РАЗНЫЕ ВОПРОСЫ, И РАСХОЖДЕНИЕ МЕЖДУ НИМИ ЗАКОННО.
// Настройки говорят, КАК ЗАДУМАНО (каким адресом сайт себя объявляет), запрос —
// КАК ЕСТЬ (по какому имени за ним пришли). Витрина, открытая через туннель,
// честно остаётся не витриной для ворот и витриной для метаданных: первое решает
// доступ живого человека, второе — что напечатано в уже собранной странице.

/**
 * Собран ли этот экземпляр КАК ВИТРИНА.
 *
 * Спрашивают метаданные страниц, карта сайта и `robots.txt` — у них нет запроса,
 * и единственное, что они знают о себе, это адрес из настроек.
 */
export function isShowcaseBuild(): boolean {
  return isShowcaseOrigin(getAppConfig().url)
}
