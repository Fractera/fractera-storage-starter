/** Папки, которые узлу не принадлежат. Сегодня одна; список — не константа. */
export const FOREIGN_DIRS = new Set(["WEB4-ITEMS"])

/** Имя папки принадлежит чужому продукту? Зовётся в каждом обходе дерева. */
export const isForeign = (name) => FOREIGN_DIRS.has(name)

/**
 * Сторож НАД сторожем: список корней обхода не должен содержать чужого.
 * 🔒 Нужен потому, что у обходчика с белым списком корней граница невидима —
 * её не видно ни в коде, ни в выводе. Дописал кто-то `microservices` в список,
 * и сторож начнёт судить чужой продукт, оставаясь при этом «зелёным по форме».
 * Возвращает строку нарушения или `null`.
 */
export function foreignRootInList(roots, who) {
  const bad = [...roots].filter((r) => isForeign(String(r).replace(/^[.\/\\]+/, "")))
  if (!bad.length) return null
  return `${who}: в список корней обхода попало чужое — ${bad.join(", ")}. ` +
    "За этой границей лежат службы из чужих репозиториев; судить их правилами узла нельзя. " +
    "Причина целиком — в шапке scripts/microservices-boundary.mjs."
}
