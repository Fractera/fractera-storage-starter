/* Сервис-воркер приложения (шаг 504).
 *
 * 🔒 ГЛАВНОЕ РЕШЕНИЕ ЭТОГО ФАЙЛА — СТРАТЕГИЯ, А НЕ КОД.
 *
 * Сервис-воркер даёт офлайн и мгновенное повторное открытие, и он же — источник
 * самой дорогой жалобы в таких проектах: «я поменял текст на сайте, а в
 * приложении он старый». Причина всегда одна: воркер отдаёт СТРАНИЦУ из кеша.
 * У нас это недопустимо вдвойне — панель управления меняет настройки и тексты БЕЗ
 * пересборки, то есть кешированная страница расходится с настоящей в ту же минуту.
 *
 * Поэтому здесь стратегия, при которой устаревшая страница невозможна по
 * построению:
 *
 *   • ДОКУМЕНТЫ (HTML) — только из сети. Кеш используется ИСКЛЮЧИТЕЛЬНО когда
 *     сети нет: тогда открывается последняя виденная версия вместо экрана ошибки
 *     браузера. Пока сеть есть, пользователь всегда видит настоящую страницу.
 *   • СТАТИКА ПО ХЕШУ (`/_next/static/…`) — из кеша. Её адрес меняется при каждой
 *     сборке, поэтому устареть она не может физически: новый код = новый адрес.
 *   • ШРИФТЫ СВОЕГО СЕРВЕРА (`/fonts/…`, шаг 315) — тем же правилом, что статика:
 *     без них страница из кеша рисовалась бы системным шрифтом. Кеш статики
 *     привязан к версии воркера и чистится при каждой сборке — устареть шрифт
 *     дольше одной сборки не может.
 *   • ВСЁ ОСТАЛЬНОЕ (api, изображения) — воркер не трогает.
 *
 * Отдельной офлайн-страницы нет намеренно: она потребовала бы слов на всех
 * языках, а слова — это партия перевода. Страница, которую посетитель уже
 * открывал, откроется из кеша и так; страница, которую он не открывал, честно
 * покажет ошибку сети.
 */

/* 🛑 ВЕРСИЯ ПРИХОДИТ ИЗ АДРЕСА САМОГО ВОРКЕРА, А НЕ ПИШЕТСЯ ЗДЕСЬ КОНСТАНТОЙ.
 *
 * ✗ ОПЛАЧЕНО БЕЛЫМ ЭКРАНОМ У ВЛАДЕЛЬЦА 2026-09-19. Здесь стояло `const VERSION =
 * "v1"` — строка, которая не менялась НИКОГДА. Отсюда цепочка, в которой каждое
 * звено выглядит исправным:
 *   1) файл воркера между сборками побайтно одинаков;
 *   2) значит браузер не считает его обновлённым и НЕ активирует заново;
 *   3) значит `activate` не выполняется, и кеш страниц не вычищается никогда;
 *   4) при обрыве связи воркер честно отдаёт страницу из этого вечного кеша;
 *   5) та страница ссылается на `/_next/static/…` ПРОШЛОЙ сборки, а каждая новая
 *      сборка заменяет хеши — файлов больше нет;
 *   6) скрипты не грузятся → белый экран, при том что сервер отвечает 200.
 *
 * 🔒 ЛЕЧЕНИЕ БЕЗ ГЕНЕРАЦИИ ФАЙЛА ПРИ СБОРКЕ. Регистрация зовёт `/sw.js?v=<метка
 * сборки>`; воркер читает метку из собственного адреса. Новая сборка — новый
 * адрес скрипта, браузер видит НОВУЮ регистрацию, `activate` выполняется и
 * удаляет кеши прошлой версии по имени. Файл при этом остаётся статическим и
 * лежит в git как есть: генерировать его сборкой значило бы держать в дереве
 * файл, который меняется при каждом коммите.
 *
 * 🛑 Метка чистится от всего, кроме букв, цифр, точки и дефиса: она попадает в
 * ИМЯ КЕША, а имя кеша не место для содержимого чужого запроса.
 */
const VERSION = (new URL(self.location.href).searchParams.get("v") || "dev").replace(/[^A-Za-z0-9.-]/g, "").slice(0, 40) || "dev";
const PAGES = `pages-${VERSION}`;
const ASSETS = `assets-${VERSION}`;

self.addEventListener("install", () => {
  // Ждать нечего: ничего не предзагружаем — предзагрузка означала бы решать за
  // пользователя, какие страницы ему понадобятся.
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      // Кеши прошлых версий воркера удаляются целиком: держать их — значит
      // копить на устройстве мусор, который никто никогда не прочитает.
      const keys = await caches.keys();
      await Promise.all(keys.filter((k) => k !== PAGES && k !== ASSETS).map((k) => caches.delete(k)));
      await self.clients.claim();

      // 🔒 СТРАНИЦА ПЕРВОГО ВИЗИТА — ИНАЧЕ ОБЕЩАНИЕ ОФЛАЙНА ЛОЖНО.
      //
      // Воркер рождается ПОСЛЕ загрузки страницы, ради которой посетитель
      // пришёл, — значит та страница прошла мимо него и в кеш не попала. В кеше
      // оказываются только СЛЕДУЮЩИЕ переходы, и посетитель, потерявший сеть на
      // первой же странице, получает ошибку браузера на том, что видел секунду
      // назад. Дефект найден руками 2026-08-13: сайт был открыт, а в офлайне не
      // открылся.
      //
      // Закону «ничего не предзагружаем» это не противоречит. Предзагрузка —
      // догадка о страницах, которые посетителю ПОНАДОБЯТСЯ; здесь же мы
      // спрашиваем браузер, что открыто ПРЯМО СЕЙЧАС, и сохраняем ровно это.
      // Догадки нет: страница уже на экране.
      //
      // Сбой не имеет права свалить активацию — воркер без одной записи в кеше
      // полезнее, чем воркер, который не активировался.
      const clients = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
      const pages = await caches.open(PAGES);
      await Promise.all(
        clients.map(async (client) => {
          const url = new URL(client.url);
          if (url.origin !== self.location.origin) return;
          if (await pages.match(url.href)) return;
          try {
            const res = await fetch(url.href, { credentials: "same-origin" });
            if (res.ok) await pages.put(url.href, res);
          } catch {
            /* сети нет или страница отказала — не повод ломать активацию */
          }
        }),
      );
    })(),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;

  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  // Статика по хешу — из кеша, иначе из сети с сохранением.
  if (url.pathname.startsWith("/_next/static/") || url.pathname.startsWith("/fonts/")) {
    event.respondWith(
      caches.open(ASSETS).then(async (cache) => {
        const hit = await cache.match(req);
        if (hit) return hit;
        const res = await fetch(req);
        if (res.ok) cache.put(req, res.clone());
        return res;
      }),
    );
    return;
  }

  // Документы — сеть первой. Кеш только как замена экрану ошибки.
  const isDocument = req.mode === "navigate" || (req.headers.get("accept") || "").includes("text/html");
  if (!isDocument) return;

  /* 🔒 СТАРАЯ СТРАНИЦА — ТОЛЬКО БЕЗ СЕТИ (285-8). ✗ Измерено 2026-09-24 в браузере владельца: воркер отдал страницу
   * из кеша прошлой сборки, хотя сеть была, — сервер на секунды пропал при развёртывании (переключение сборки,
   * туннель), и ветка «нет сети» сработала на «сервер не ответил». Владелец видел прошлые версии и называл это
   * «откатами». Теперь: сеть есть — запрос повторяется с растущей паузой, и если сервер всё ещё молчит, отдаётся
   * крошечная страница, которая сама перезагрузится (без слов — она не требует перевода); старая страница при живой
   * сети не отдаётся НИКОГДА. Сети нет — последняя виденная, как и задумано. */
  event.respondWith(
    (async () => {
      const online = self.navigator.onLine !== false;
      const attempts = online ? 4 : 1;
      for (let i = 0; i < attempts; i++) {
        try {
          /* 🔒 ВСЕГДА СВЕРЯТЬСЯ С СЕРВЕРОМ (владелец 2026-09-30, замер в Chrome): обычный fetch идёт через HTTP-кеш браузера,
           * а Next отдаёт HTML с `s-maxage=300, stale-while-revalidate=…` — для браузера это «свежесть 0, старое можно отдавать
           * почти год, обновляясь в фоне». Chrome так и делал: после каждой публикации вернувшийся посетитель один раз видел
           * ПРЕДЫДУЩУЮ версию. `no-cache` — сверка с сервером на каждый переход. `redirect: "manual"`: навигации нельзя вернуть
           * ответ, прошедший переадресацию (браузер сам последует за opaqueredirect). */
          const res = await fetch(req.url, { cache: "no-cache", credentials: "same-origin", redirect: "manual" });
          if (res.ok) {
            const cache = await caches.open(PAGES);
            cache.put(req, res.clone());
          }
          return res;
        } catch {
          if (i < attempts - 1) await new Promise((r) => setTimeout(r, 700 * (i + 1)));
        }
      }
      if (!online) {
        // Два чтения, а не одно: запись могла лечь сюда либо навигационным
        // запросом (обычный переход), либо строковым адресом (страница первого
        // визита, сохранённая при активации). Ключи разной природы, и
        // сопоставление по объекту запроса не обязано находить строковый ключ —
        // цена промаха тут ровно та ошибка браузера, ради которой всё и писано.
        const cached = (await caches.match(req)) || (await caches.match(req.url));
        if (cached) return cached;
      }
      return new Response(
        '<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta http-equiv="refresh" content="3"><title>…</title><body style="margin:0;display:grid;place-items:center;height:100vh;font:600 2rem system-ui;opacity:.5">⟳</body>',
        { status: 503, headers: { "content-type": "text/html; charset=utf-8", "cache-control": "no-store", "retry-after": "3" } },
      );
    })(),
  );
});
